#!/usr/bin/env node
// Generate src/services.generated.ts from the live x402 manifest.
// Usage: node scripts/gen-services.mjs [manifestUrl]
// Default: https://milypay.xyz/.well-known/x402 (override with MILYPAY_MANIFEST_URL).
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const url = process.argv[2] || process.env.MILYPAY_MANIFEST_URL || "https://milypay.xyz/.well-known/x402";
const res = await fetch(url, { headers: { accept: "application/json" } });
if (!res.ok) throw new Error(`manifest ${url} -> HTTP ${res.status}`);
const manifest = await res.json();

// Free / token-gated routes that the paid-only manifest does not list.
const FREE = [
  { method: "GET", path: "/au-asic-extract", price: "0", description: "ASIC extract catalogue (Acceleon UAT test mode)." },
  { method: "GET", path: "/au-asic-extract/status/{id}?token={token}", price: "0", description: "Extract status (buyer token from purchase)." },
  { method: "GET", path: "/au-asic-extract/extract/{id}?token={token}", price: "0", description: "Download extract JSON / PDF (buyer token from purchase)." },
  { method: "GET", path: "/ramp/moneygram", price: "0", description: "MoneyGram funding status (pre-x402 wallet top-up)." },
  { method: "POST", path: "/ramp/moneygram/session", price: "0", description: "Create MoneyGram sandbox session (on-ramp / off-ramp)." },
  { method: "GET", path: "/status", price: "0", description: "Service health (JSON)." },
  { method: "GET", path: "/stats", price: "0", description: "Usage stats." },
];

function idFor(method, path) {
  const base = path.split("?")[0].replace(/^\//, "").replace(/\{[^}]+\}/g, "").replace(/\/+/g, "/").replace(/\/$/, "");
  return method === "GET" ? base : `${method} ${base}`;
}

const seen = new Set();
const services = [];
for (const e of [...(manifest.endpoints || []), ...FREE]) {
  const id = idFor(e.method, e.path);
  const key = `${e.method} ${e.path}`;
  if (seen.has(key)) continue;
  seen.add(key);
  services.push({ id, method: e.method, path: e.path, price: String(e.price), description: e.description || "" });
}

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "services.generated.ts");
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/gen-services.mjs from ${url}. Do not edit by hand.\n` +
    `// Regenerate: npm run gen:services\n` +
    `import type { Service } from "./services.js";\n\n` +
    `export const GENERATED_AT = ${JSON.stringify(new Date().toISOString())};\n` +
    `export const GENERATED_SERVICES: Service[] = ${JSON.stringify(services, null, 2)};\n`,
);
console.log(`wrote ${services.length} services to ${out}`);
